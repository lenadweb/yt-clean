const fs = require('node:fs');
const path = require('node:path');
const prettier = require('prettier');
require('ts-node').register();
require('tsconfig-paths/register');

const { CATEGORIES, FEATURES } = require('./src/shared/featureConfig');
const { DEFAULT_STORAGE } = require('./src/shared/storage/config');
const { MANAGED_FEATURE_IDS } = require('./src/shared/presets');
const { UrlRegExps } = require('./src/shared/const');
const messages = require('./src/_locales/en/messages.json');

const label = (key) => messages[key]?.message ?? key;
const cell = (value) => String(value).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const scope = (feature) =>
    feature.urlRegExp
        ? feature.urlRegExp
              .map(
                  (pattern) =>
                      Object.keys(UrlRegExps).find(
                          (key) => UrlRegExps[key].source === pattern.source
                      ) ?? pattern.source
              )
              .join(', ')
        : 'all pages';

const lines = [
    '# Feature catalog',
    '',
    '<!-- Generated by featureCatalog.js. Run npm run docs:features after config changes. -->',
    '',
    `This catalog lists all ${FEATURES.length} active declarative features. Labels, scopes,`,
    'actions and fresh-install defaults come from the feature config and storage defaults.',
    'New installs use the Balanced preset with the extension enabled. Existing saved',
    'settings are preserved. Watch means `/watch` with a nonempty `v` parameter;',
    'Channel includes handle, `/c/`, `/channel/` and `/user/` pages and their tabs.',
    '',
];

CATEGORIES.forEach((category) => {
    lines.push(
        `## ${label(category.title)}`,
        '',
        '| Section | Feature id | UI label | Actions | Scope | Default |',
        '| --- | --- | --- | --- | --- | --- |'
    );
    category.sections.forEach((section) => {
        section.features.forEach((feature) => {
            const actions = [
                ...new Set(feature.actions.map((action) => action.action)),
            ];
            if (feature.onChange) actions.push('onChange');
            lines.push(
                `| ${[
                    label(section.title),
                    `\`${feature.id}\``,
                    label(feature.title ?? section.title),
                    actions.join(', '),
                    scope(feature),
                    DEFAULT_STORAGE[feature.id].enabled ? 'on' : 'off',
                ]
                    .map(cell)
                    .join(' | ')} |`
            );
        });
    });
    lines.push('');
});

const excluded = FEATURES.filter(
    (feature) => !MANAGED_FEATURE_IDS.includes(feature.id)
)
    .map((feature) => `\`${feature.id}\``)
    .join(', ');
lines.push(
    '## Presets and filters',
    '',
    'Light, Balanced and Custom each keep their saved cleanup settings. Editing',
    'Light or Balanced updates that preset after a confirmation; Reset restores its defaults.',
    `Switching or resetting presets preserves these preferences: ${excluded}.`,
    '',
    'Keyword and duration filters are separate from the declarative features and presets.',
    'They are enabled but inactive until configured. Search results are not filtered.',
    'Duration filtering leaves live streams and videos without a readable duration visible.',
    'Watched-video hiding starts at 34% progress. Endless home feed extends only the All tab.',
    '',
    '## Behavior notes',
    '',
    '- Hiding the Shorts menu item only changes navigation. Hide Shorts sections controls content.',
    '- Disabling hover previews hides their renderer and pauses preview playback; normal videos remain playable.',
    '- Hiding channel trailers pauses them without removing YouTube DOM nodes. Disabling allows playback again.',
    '- Original titles are fetched from public youtube.com oEmbed metadata; no third-party service is used.',
    '- Original audio applies once per video and respects subsequent manual track changes. Re-enabling reapplies it.',
    '- Hiding watch recommendations preserves functional side panels; normal layout centers when none are needed.',
    '- Hiding Home keeps the YouTube logo. Home redirect only sends signed-in users to Subscriptions.',
    '- Enabling every Explore option hides the complete Explore section, including collapsed entries.',
    '- Codec and bandwidth changes may need a player reload to affect the currently selected stream.',
    '- Shorts speed and auto-next controls are not currently available.',
    '',
    '## Maintenance',
    '',
    '- Regenerate with `npm run docs:features`; CI runs `npm run docs:features:check`.',
    '- Never rename released feature ids without a storage migration.',
    '- Choose preset membership or exclusion explicitly when adding a feature.',
    '- Section-level hideWhenAllEnabled actions are not separate settings.',
    '- Selector behavior still needs verification against current YouTube DOM.',
    ''
);

const destination = path.join(__dirname, 'docs/feature-catalog.md');
const generate = async () => {
    const options = await prettier.resolveConfig(destination);
    const output = await prettier.format(lines.join('\n'), {
        ...options,
        filepath: destination,
    });
    if (process.argv.includes('--check')) {
        if (
            !fs.existsSync(destination) ||
            fs.readFileSync(destination, 'utf8') !== output
        ) {
            console.error(
                'Feature catalog is out of date. Run npm run docs:features.'
            );
            process.exitCode = 1;
        }
    } else {
        fs.writeFileSync(destination, output);
    }
};
generate().catch((error) => {
    console.error(error);
    process.exitCode = 1;
});
